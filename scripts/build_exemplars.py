"""Build the centroid exemplar file from policy text and the v1 development set.

Sources, and only these two:
  - the policy-derived phrasings already in data/semantic_exemplars.json
  - held-out v1, which was retired from reporting after the `do i have` fix and is now a
    development set

Held-out v2 is never read here, and tests/test_semantic_stage.py asserts that no v2 line
appears in the output. Selection is seeded and register-balanced so the file can be
regenerated exactly.

Usage: python scripts/build_exemplars.py [--per-register 4]
"""
from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
POLICY = ROOT / "data" / "semantic_exemplars.json"
V1 = ROOT / "data" / "paraphrases_heldout_v1.json"
OUT = ROOT / "data" / "semantic_exemplars_expanded.json"
SEED = 20260905


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--per-register", type=int, default=4)
    args = parser.parse_args(argv)

    policy = json.loads(POLICY.read_text(encoding="utf-8"))
    v1 = json.loads(V1.read_text(encoding="utf-8"))
    rng = random.Random(SEED)

    out: dict = {
        "_note": "Generated by scripts/build_exemplars.py from policy text and held-out v1 "
                 "(a development set since the `do i have` fix retired it from reporting). "
                 "Held-out v2 is never read. Regenerate with the same seed to reproduce.",
        "_sources": ["data/semantic_exemplars.json", "data/paraphrases_heldout_v1.json"],
        "_seed": SEED,
        "_per_register": args.per_register,
    }
    for category, phrases in policy.items():
        if category.startswith("_"):
            continue
        chosen = list(phrases)
        rows = v1["categories"].get(category, [])
        by_register: dict[str, list[str]] = {}
        for entry in rows:
            by_register.setdefault(entry["register"], []).append(entry["text"])
        for register in sorted(by_register):
            pool = sorted(by_register[register])
            chosen += rng.sample(pool, min(args.per_register, len(pool)))
        out[category] = chosen
        print(f"{category:24} {len(phrases)} policy + "
              f"{len(chosen) - len(phrases)} from v1 = {len(chosen)}")

    OUT.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
