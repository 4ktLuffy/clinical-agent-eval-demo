"""The held-out set must stay held out, and stay honestly labelled."""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from clinical_agent.guardrail import REFUSAL_CATEGORIES  # noqa: E402

HELDOUT = ROOT / "data" / "paraphrases_heldout_v2.json"
DATA = json.loads(HELDOUT.read_text(encoding="utf-8"))


def _norm(text: str) -> str:
    return re.sub(r"[^a-z0-9 ]", "", text.lower())


def test_every_category_meets_the_floor():
    for category in REFUSAL_CATEGORIES:
        for half in ("categories", "negatives"):
            rows = DATA[half][category]
            assert len(rows) >= 60, f"{half}/{category} has {len(rows)}, floor is 60"


def test_every_paraphrase_is_distinct():
    seen = [_norm(e["text"])
            for half in ("categories", "negatives")
            for rows in DATA[half].values() for e in rows]
    assert len(seen) == len(set(seen)), "duplicates would inflate recall or precision"


def test_positives_and_negatives_do_not_overlap():
    """A line cannot be both refusable and in scope. Any overlap would make precision and
    recall disagree about the same sentence."""
    positives = {_norm(e["text"]) for rows in DATA["categories"].values() for e in rows}
    negatives = {_norm(e["text"]) for rows in DATA["negatives"].values() for e in rows}
    assert not (positives & negatives), sorted(positives & negatives)[:5]


def test_no_overlap_with_the_tuned_conversation_set():
    """Held out means the guardrail was never fitted to these lines. Any overlap with
    data/conversations.json would make the recall number partly a memory test."""
    conversations = json.loads((ROOT / "data" / "conversations.json").read_text())
    existing = {_norm(t["text"]) for c in conversations for t in c["turns"]}
    held = {_norm(e["text"])
            for half in ("categories", "negatives")
            for rows in DATA[half].values() for e in rows}
    assert not (existing & held), sorted(existing & held)[:5]


def test_all_four_registers_are_present_in_every_category():
    for half in ("categories", "negatives"):
        for category, rows in DATA[half].items():
            registers = {e["register"] for e in rows}
            assert registers == set(DATA["registers"]), f"{half}/{category}: {sorted(registers)}"


def test_reviewed_flag_is_present_and_explicit():
    """A recall number computed against unreviewed labels carries the generator's mistakes.
    The flag must exist so the docs can say which it is; this test does not require it to
    be true, only that nobody silently deletes it."""
    assert "reviewed" in DATA
    assert isinstance(DATA["reviewed"], bool)


def test_only_the_measurement_script_reads_the_held_out_set():
    """Nothing tunes on v2, ever. The cheapest structural guarantee of that is that no
    other script, source file or test may even open it: a file nothing reads cannot have
    been fitted to. scripts/generate_paraphrases.py writes it, and heldout_recall.py
    measures against it. Anything else naming it is a leak."""
    allowed = {"heldout_recall.py", "generate_paraphrases.py", "test_heldout_paraphrases.py"}
    offenders = []
    for path in list((ROOT / "src").rglob("*.py")) + list((ROOT / "scripts").rglob("*.py")) \
            + list((ROOT / "tests").rglob("*.py")):
        if path.name in allowed:
            continue
        if "paraphrases_heldout_v2" in path.read_text(encoding="utf-8"):
            offenders.append(str(path.relative_to(ROOT)))
    assert not offenders, f"these read the held-out set: {offenders}"


def test_v1_is_frozen_and_not_read_by_the_measurement_script():
    """v1 measured a guardrail that no longer exists (the `do i have` fix changed it).
    It stays in the tree because FINDINGS quotes it, but nothing may score against it."""
    v1 = json.loads((ROOT / "data" / "paraphrases_heldout_v1.json").read_text(encoding="utf-8"))
    assert v1.get("frozen") is True
    measure = (ROOT / "scripts" / "heldout_recall.py").read_text(encoding="utf-8")
    assert "paraphrases_heldout_v1" not in measure


def test_v2_does_not_overlap_v1():
    v1 = json.loads((ROOT / "data" / "paraphrases_heldout_v1.json").read_text(encoding="utf-8"))
    earlier = {_norm(e["text"]) for half in ("categories", "negatives")
               for rows in v1[half].values() for e in rows}
    current = {_norm(e["text"]) for half in ("categories", "negatives")
               for rows in DATA[half].values() for e in rows}
    assert not (earlier & current), sorted(earlier & current)[:5]


def test_generator_is_not_a_stage_model():
    """The set must not be generated by a model the guardrail's own stage uses."""
    assert "gpt-oss-120b" not in DATA["generator"]
    assert DATA["generator"] != "openai/gpt-oss-20b"


def test_no_held_out_v2_line_appears_in_any_exemplar_file():
    """The centroid may learn from policy text and from v1, which was retired to a
    development set. If a v2 line ever reached an exemplar file, every v2 number would be
    scored against phrasings the stage had been shown, and the set would stop being held
    out. Compared on normalised text, so a requote or a case change cannot slip through."""
    root = ROOT

    def norm(text: str) -> str:
        return re.sub(r"[^a-z0-9]", "", text.lower())

    held = {norm(e["text"])
            for half in ("categories", "negatives")
            for rows in DATA[half].values() for e in rows}

    for name in ("semantic_exemplars.json", "semantic_exemplars_expanded.json"):
        path = root / "data" / name
        if not path.exists():
            continue
        raw = json.loads(path.read_text(encoding="utf-8"))
        for category, phrases in raw.items():
            if category.startswith("_"):
                continue
            for phrase in phrases:
                assert norm(phrase) not in held, f"{name}: v2 line used as an exemplar: {phrase!r}"
